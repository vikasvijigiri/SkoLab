# Template for generating checklists
checklist_template = """# {filename_prefix} — {title}

> **Purpose:** {purpose}
> Copilot: {copilot}
> A release is only approved when every section shows `[x]` on all items.

---

## How to use this file

- Mark each item `[x]` as you complete it.
- Run `grep -c '\\[ \\]' {filename}` to count remaining open items — zero means ready.
- Copilot instructions at the top of each section describe what to verify automatically where possible.

---
{pillars_content}
## Final Go / No-Go Gate

Run this command to count open items before release approval:

```bash
grep -c '\\[ \\]' {filename}
```

**Approval is granted only when the output is `0`.**

| Check | Status |
|---|---|
{gate_rows}
| **Final Sign-off** | `[ ]` ______________ Date: ______________ |

---

*Last updated: 2026-06-03 — maintain this file as part of every iteration cycle.*
"""

def generate_checklists():
    print("Generating checklists...", flush=True)
    for key, data in checklists_data.items():
        filename_prefix = key
        filename = f"{key}_CHECKLIST.md"
        file_path = os.path.join(CHECKLISTS_DIR, filename)
        
        pillars_content = ""
        gate_rows = ""
        for idx, pillar in enumerate(data["pillars"]):
            pillar_num = idx + 1
            pillars_content += f"\n## Pillar {pillar_num} — {pillar['name']}\n\n"
            pillars_content += f"> **Copilot:** Verify that the code satisfies the '{pillar['name']}' constraints in the current PR diff.\n\n"
            for item in pillar["items"]:
                clean_item = item.lstrip("- ").lstrip("[ ] ")
                pillars_content += f"- [ ] {clean_item}\n"
            pillars_content += f"\n**Sign-off:** `[ ]` {pillar['name']} verified by _______________  Date: _______________\n\n---\n"
            gate_rows += f"| All Pillar {pillar_num} items complete | `[ ]` |\n"
            
        final_content = checklist_template.format(
            filename_prefix=filename_prefix.replace("_", " "),
            title=data["title"],
            purpose=data["purpose"],
            copilot=data["copilot"],
            filename=filename,
            pillars_content=pillars_content,
            gate_rows=gate_rows
        )
        
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(final_content)
        print(f"Created: {filename}", flush=True)

if __name__ == "__main__":
    generate_checklists()
